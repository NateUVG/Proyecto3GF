pub struct Lienzo<'a> {
    pub color: &'a mut [u32],
    pub ancho: usize,
    pub alto: usize,
}

impl Lienzo<'_> {
    fn pixel(&mut self, x: i32, y: i32, c: u32) {
        if x >= 0 && y >= 0 && (x as usize) < self.ancho && (y as usize) < self.alto {
            self.color[y as usize * self.ancho + x as usize] = c;
        }
    }

    fn texto_plano(&mut self, x: i32, y: i32, texto: &str, c: u32, escala: i32) {
        let mut cx = x;
        for ch in texto.chars() {
            for (fila, bits) in glifo(ch.to_ascii_uppercase()).iter().enumerate() {
                for col in 0..5 {
                    if bits & (0x10 >> col) != 0 {
                        for ey in 0..escala {
                            for ex in 0..escala {
                                self.pixel(cx + col * escala + ex, y + fila as i32 * escala + ey, c);
                            }
                        }
                    }
                }
            }
            cx += 6 * escala;
        }
    }

    pub fn texto(&mut self, x: i32, y: i32, texto: &str, c: u32, escala: i32) {
        self.texto_plano(x + 1, y + 1, texto, 0x000814, escala);
        self.texto_plano(x, y, texto, c, escala);
    }

    pub fn ancho_texto(texto: &str, escala: i32) -> i32 {
        texto.chars().count() as i32 * 6 * escala
    }

    pub fn marcador(&mut self, x: i32, y: i32, r: i32, c: u32) {
        let largo = (r / 3).max(3);
        for i in 0..largo {
            for (sx, sy) in [(-1, -1), (1, -1), (-1, 1), (1, 1)] {
                self.pixel(x + sx * (r - i), y + sy * r, c);
                self.pixel(x + sx * r, y + sy * (r - i), c);
            }
        }
    }

    pub fn panel(&mut self, x: i32, y: i32, ancho: i32, alto: i32) {
        for py in y.max(0)..(y + alto).min(self.alto as i32) {
            for px in x.max(0)..(x + ancho).min(self.ancho as i32) {
                let i = py as usize * self.ancho + px as usize;
                self.color[i] = (self.color[i] >> 2) & 0x3F3F3F;
            }
        }
    }
}
